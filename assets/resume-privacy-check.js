/* HireWire resume privacy check (/resume-privacy-check.html, /de/lebenslauf-datenschutz-check.html).
   Language-neutral: questions, points, bands and fixes are all in the page's HTML (generated by work/pagesbuild/quiz_rpc.py).
   No storage, no network, no analytics: answers live only in the form until the page is closed. */
(function(){
  'use strict';
  function score(root){
    const qs = Array.prototype.slice.call(root.querySelectorAll('fieldset[data-q]'));
    const res = { total:0, open:[], items:[] };
    qs.forEach(function(f){
      const c = f.querySelector('input[type=radio]:checked');
      if (!c){ res.open.push(f.dataset.q); return; }
      const p = +c.dataset.p || 0;
      res.total += p;
      const fix = f.querySelector('[data-fix]');
      if (p > 0) res.items.push({ q:f.dataset.q, p:p, fix:fix ? fix.textContent : '', legend:f.querySelector('legend').lastChild.textContent.trim() });
    });
    res.count = qs.length;
    res.items.sort(function(a, b){ return b.p - a.p; });   // stable: ties keep question order
    return res;
  }
  function band(root, total){
    const bs = Array.prototype.slice.call(root.querySelectorAll('[data-band]'));
    let pick = bs[0];
    bs.forEach(function(b){ if (total >= +b.dataset.min) pick = b; });
    return { idx:+pick.dataset.band, title:pick.dataset.title, text:pick.textContent };
  }
  function esc(s){ return String(s).replace(/[&<>"']/g, function(c){ return { '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;' }[c]; }); }
  function init(){
    const root = document.getElementById('rpcTool'); if (!root) return;
    const S = document.getElementById('rpcStrings').dataset;
    const max = +root.dataset.max || 0;
    const status = document.getElementById('rpcStatus'), result = document.getElementById('rpcResult'), out = document.getElementById('rpcOut');
    let last = null;
    function show(){
      const r = score(root);
      if (r.open.length){
        status.textContent = S.need.replace('{n}', r.count).replace('{k}', r.open.length);
        const f = document.getElementById('q-' + r.open[0]);
        if (f){ f.classList.add('qmiss'); const i = f.querySelector('input'); if (i) i.focus(); }
        return null;
      }
      status.textContent = '';
      const b = band(root, r.total);
      const pct = max ? Math.round(r.total / max * 100) : 0;
      let h = '<div class="rpc-head lvl' + b.idx + '"><span class="rpc-badge">' + esc(b.title) + '</span>' +
        '<span class="rpc-num">' + esc(S.score) + ': <b>' + r.total + '</b> / ' + max + '</span></div>' +
        '<div class="rpc-bar" role="img" aria-label="' + r.total + ' / ' + max + '"><i style="width:' + pct + '%"></i></div>' +
        '<p>' + esc(b.text) + '</p>';
      if (r.items.length){
        h += '<h3>' + esc(S.fixes) + '</h3><ol class="rpc-fixes">' + r.items.map(function(it){
          return '<li><b>' + esc(it.legend) + '</b><span>' + esc(it.fix) + '</span></li>';
        }).join('') + '</ol>';
      } else h += '<p>' + esc(S.none) + '</p>';
      out.innerHTML = h;
      result.hidden = false;
      try { result.focus({ preventScroll:true }); result.scrollIntoView({ behavior:'smooth', block:'start' }); } catch(e){}
      last = { r:r, b:b };
      return last;
    }
    function text(){
      if (!last) return '';
      const L = [last.b.title + ' — ' + S.score + ': ' + last.r.total + ' / ' + max, ''];
      if (last.r.items.length) last.r.items.forEach(function(it, i){ L.push((i + 1) + '. ' + it.fix); });
      else L.push(S.none);
      L.push('', S.share);
      return L.join('\n');
    }
    root.addEventListener('change', function(ev){
      const f = ev.target.closest && ev.target.closest('fieldset');
      if (f) f.classList.remove('qmiss');
      if (!result.hidden) show();   // keep an open result in step with edits
    });
    document.getElementById('rpcGo').addEventListener('click', show);
    document.getElementById('rpcReset').addEventListener('click', function(){
      document.getElementById('rpcForm').reset();
      Array.prototype.forEach.call(root.querySelectorAll('.qmiss'), function(f){ f.classList.remove('qmiss'); });
      result.hidden = true; out.innerHTML = ''; status.textContent = ''; last = null;
      const first = root.querySelector('input'); if (first) first.focus();
    });
    document.getElementById('rpcCopy').addEventListener('click', function(){
      const t = text();
      const done = function(ok){ status.textContent = ok ? S.copied : S.copyfail; };
      if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(t).then(function(){ done(true); }, function(){ done(false); });
      else done(false);
    });
    window.HWResumeCheck = { score:function(){ return score(root); }, show:show, text:text };
  }
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init); else init();
})();
